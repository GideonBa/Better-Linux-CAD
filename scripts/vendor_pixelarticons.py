#!/usr/bin/env python3
"""Vendor the catalog's pinned SVG subset and lossless 24px Qt XPM masks.

Regeneration only: requires rsvg-convert and Pillow. Application builds use the
checked-in masks with QtGui; no SVG plugin, Python or download is needed at runtime.
"""

import argparse
import hashlib
import io
import json
from pathlib import Path
import shutil
import subprocess

from PIL import Image


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("upstream", type=Path, help="Extracted Pixelarticons source directory")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1] / "assets/gui/pixelarticons"
    catalog = json.loads((root / "catalog.json").read_text())
    package = json.loads((args.upstream / "package.json").read_text())
    if package["version"] != catalog["version"]:
        raise ValueError("Upstream package version differs from the pinned catalog")
    for directory in ("svg", "masks"):
        (root / directory).mkdir(exist_ok=True)
    shutil.copyfile(args.upstream / "LICENSE", root / "LICENSE")
    hashes = {}
    for name in catalog["icons"]:
        source = (args.upstream / "svg" / f"{name}.svg").read_bytes()
        (root / "svg" / f"{name}.svg").write_bytes(source)
        png = subprocess.run(
            ["rsvg-convert", "--width", "24", "--height", "24"],
            input=source, stdout=subprocess.PIPE, check=True,
        ).stdout
        image = Image.open(io.BytesIO(png)).convert("RGBA")
        if image.size != (24, 24) or not set(image.getchannel("A").getdata()) <= {0, 255}:
            raise ValueError(f"{name} is not an opaque/transparent 24px pixel-grid icon")
        rows = [
            '"' + ''.join("." if image.getpixel((x, y))[3] else " " for x in range(24)) + '"'
            for y in range(24)
        ]
        mask = (
            "/* XPM */\n/* Generated from the adjacent MIT-licensed Pixelarticons SVG. */\n"
            f"static const char *{name.replace('-', '_')}_xpm[] = {{\n"
            '"24 24 2 1",\n"  c None",\n". c #ffffff",\n'
            + ",\n".join(rows) + "\n};\n"
        ).encode()
        (root / "masks" / f"{name}.xpm").write_bytes(mask)
        hashes[name] = {"svg_sha256": hashlib.sha256(source).hexdigest(),
                        "mask_sha256": hashlib.sha256(mask).hexdigest()}
    manifest = {
        key: catalog[key] for key in ("upstream", "version", "revision", "license", "grid")
    }
    manifest["license_sha256"] = hashlib.sha256((root / "LICENSE").read_bytes()).hexdigest()
    manifest["files"] = hashes
    (root / "source-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    resources = ["LICENSE", "catalog.json", "source-manifest.json"]
    resources += [f"masks/{name}.xpm" for name in catalog["icons"]]
    (root / "resources.cmake").write_text(
        "# Generated by scripts/vendor_pixelarticons.py; committed for offline builds.\n"
        "set(BLCAD_PIXELARTICON_RESOURCES\n"
        + "".join(f"  assets/gui/pixelarticons/{name}\n" for name in resources) + ")\n"
    )
    print(f"Vendored {len(catalog['icons'])} Pixelarticons {catalog['version']} icons")


if __name__ == "__main__":
    main()
