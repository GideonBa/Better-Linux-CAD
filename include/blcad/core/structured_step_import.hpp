#pragma once

#include "blcad/core/project.hpp"

#include <cstddef>
#include <string>
#include <vector>

namespace blcad {

// Initial structured-import construction only. Geometry supplies one real
// imported Part per foreign leaf definition, one child Assembly per foreign
// assembly definition, and exact typed direct occurrences. The explicit
// synthetic root retains all foreign root placements. No foreign labels,
// traversal indices, kernel objects or new persistence records are required.
[[nodiscard]] Result<Project>
create_structured_step_project(DocumentId project_id, std::string name, StepImportSource source,
                               AssemblyDocument root, std::vector<AssemblyDocument> assemblies,
                               std::vector<PartDocument> parts);

// A strict fresh-candidate policy, not a validator for later user-authored
// imported Projects. Existing Project validation remains authoritative after
// import. Document and occurrence ids generated by this factory's caller are
// unique across the complete initial candidate; scoped ids inside shared Part
// definitions retain the existing Core ownership rules.
[[nodiscard]] Result<std::size_t>
validate_structured_step_import_candidate(const Project& project, StepImportSourceId source);

} // namespace blcad
